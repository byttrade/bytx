def _default_balance() -> dict[str, float]:
    return {'USDT': 10_000.0, 'USDC': 10_000.0}


@dataclass
class PaperConfig:
    """Paper account settings.

    ``balance`` — starting funds {currency: amount}; ``fees`` — ``PaperFees`` or (maker, taker),
    None — the exchange's default tier per its docs (:func:`~bytx.paper.default_fees`);
    ``maintenance_margin_rate`` — simplified liquidation rate (None — no liquidation);
    ``trigger_by`` — 'mark' / 'last' for TP/SL without an explicit one; ``fill_on_trades`` — resting limits
    also fill on trades through the price (live paper subscribes to the symbol's trades);
    ``default_leverage`` — leverage without ``set_leverage``; ``funding_poll`` — seconds between
    funding rate polls in live paper (None — no funding); ``book_depth`` — WS order book depth;
    ``book_wait`` — how many seconds a symbol's first order waits for the WS book before taking a REST snapshot;
    ``seed`` — client_ids generated by the SDK itself come from a deterministic generator (replay —
    always, default seed 0: same inputs → same client_ids).
    """

    balance: dict[str, float] = field(default_factory=_default_balance)
    fees: FeesArg = None
    maintenance_margin_rate: Optional[float] = 0.005
    trigger_by: str = 'mark'
    fill_on_trades: bool = True
    default_leverage: float = 1.0
    funding_poll: Optional[float] = 60.0
    book_depth: int = 50
    book_wait: float = 2.0
    seed: Optional[int] = None


class PaperExchange(Exchange):
    """Exchange with paper execution (see module). ``engine`` — the engine, ``clock`` — the clock,
    ``replay`` — the replay driver (None — live paper)."""

    is_paper = True

    def __init__(self, ccxt_exchange: Any, *, name: str, market_type: str = 'swap',
                 config: Optional[PaperConfig] = None, clock: Optional[Clock] = None,
                 replay: bool = False, **kwargs: Any) -> None:
        super().__init__(ccxt_exchange, name=name, market_type=market_type, **kwargs)
        self.config = config or PaperConfig()
        self.replay_mode = bool(replay)
        self.clock: Clock = clock or (VirtualClock() if replay else WallClock())
        self.replay: Optional['Replay'] = None
        if self._hedge is None:
            self._hedge = False
        # no batch endpoints: place_orders / cancel_orders / cancel_all go one by one
        self._ex.has = {**self._ex.has, 'createOrders': False, 'cancelOrders': False, 'cancelAllOrders': False}
        self.fees: PaperFees = resolve_fees(self.config.fees, ccxt_exchange.id, market_type)
        mmr = self.config.maintenance_margin_rate
        self.engine = PaperEngine(exchange=name, market_type=market_type, market=self._paper_market,
                                  fees=self.fees, balances=dict(self.config.balance), clock=self.clock.now_ms,
                                  hedge=bool(self._hedge), maintenance_margin_rate=mmr or 0.0,
                                  trigger_by=self.config.trigger_by, fill_on_trades=self.config.fill_on_trades,
                                  default_leverage=self.config.default_leverage, liquidation=mmr is not None)
        self._markets_cache: dict[str, Market] = {}
        self._fed: set[str] = set()
        self._feed_handles: list[Any] = []
        self._funding_task: Optional[asyncio.Task] = None
        self._sync_ids: set[str] = set()
        self._last_tickers: dict[str, Ticker] = {}
        self._book_events: dict[str, asyncio.Event] = {}
        seed = self.config.seed if self.config.seed is not None else (0 if self.replay_mode else None)
        self._cid_rng: Optional[random.Random] = random.Random(seed) if seed is not None else None
        if not self.fees.verified:
            logger.info(f'{name} paper: fee {self.fees.maker}/{self.fees.taker} not verified against the docs '
                        f'({self.fees.source}) — set PaperConfig(fees=...)')

    # ─── lifecycle ─────────────────────────────────────────────────────

    def __repr__(self) -> str:
        mode = 'replay' if self.replay_mode else 'live'
        return f'<PaperExchange {self.name} {self.market_type} {mode}>'

    async def connect(self) -> 'PaperExchange':
        if self.replay_mode:
            self._connected = True   # markets come from the recording, no network
            return self
        await super().connect()
        return self

    async def close(self) -> None:
        for h in self._feed_handles:
            h.stop()
        self._feed_handles.clear()
        self._fed.clear()
        if self._funding_task is not None:
            self._funding_task.cancel()
            self._funding_task = None
        if self.replay_mode:
            self._connected = False
            self._close_gen += 1
            if getattr(self, '_streams', None) is not None:
                await self._streams.close()
            await self._ex.close()
            return
        await super().close()

    @property
    def stream(self) -> Any:
        streams = getattr(self, '_streams', None)
        if streams is None:
            streams = self._streams = PaperStreams(self)
        return streams

    def _paper_market(self, s: str) -> Market:
        m = self._markets_cache.get(s)
        if m is None:
            m = self._markets_cache[s] = to_market(self._ex.market(s), self._ex.id)
        return m

    # ─── market: replay without network ─────────────────────────────────────────────

    def _offline(self, what: str) -> NotSupported:
        return NotSupported(f'paper replay: {what} not available in the recording (replay has no network)', exchange=self.name)

    async def order_book(self, symbol: str, depth: Optional[int] = None) -> OrderBook:
        if not self.replay_mode:
            return await super().order_book(symbol, depth)
        s = self.symbol(symbol)
        book = self.engine.book(s)
        if book is None:
            raise self._offline(f'order book {s}')
        return OrderBook(s, list(book.bids[:depth] if depth else book.bids),
                         list(book.asks[:depth] if depth else book.asks), book.timestamp, book.nonce)

    async def ticker(self, symbol: str) -> Ticker:
        if not self.replay_mode:
            return await super().ticker(symbol)
        s = self.symbol(symbol)
        t = self._last_tickers.get(s)
        book = self.engine.book(s)
        if t is None and book is None:
            raise self._offline(f'ticker {s}')
        bid = book.best_bid[0] if book is not None and book.best_bid else (t.bid if t else None)
        ask = book.best_ask[0] if book is not None and book.best_ask else (t.ask if t else None)
        return Ticker(s, bid=bid, ask=ask, last=self.engine.last_price(s) or (t.last if t else None),
                      mark=self.engine.mark_price(s), timestamp=self.clock.now_ms())

    async def server_time(self) -> int:
        return self.clock.now_ms() if self.replay_mode else await super().server_time()

    def _live_only(self, what: str) -> None:
        if self.replay_mode:
            raise self._offline(what)

    async def tickers(self, symbols: Optional[Iterable[str]] = None) -> dict[str, Ticker]:
        if self.replay_mode:
            return {s: await self.ticker(s) for s in (symbols or [])}
        return await super().tickers(symbols)

    async def trades(self, symbol: str, *, since: Optional[int] = None, limit: Optional[int] = None) -> list:
        self._live_only('REST public trades')
        return await super().trades(symbol, since=since, limit=limit)

    async def candles(self, symbol: str, timeframe: str = '1m', *, since: Optional[int] = None,
                      limit: Optional[int] = None) -> list:
        self._live_only('REST candles')
        return await super().candles(symbol, timeframe, since=since, limit=limit)

    async def funding_rate(self, symbol: str) -> FundingRate:
        self._live_only('REST funding rate')
        return await super().funding_rate(symbol)

    async def leverage_tiers(self, symbol: str) -> list:
        self._live_only('leverage tiers')
        return await super().leverage_tiers(symbol)

    # ─── market data → engine ───────────────────────────────────────────

    def _on_market(self, kind: str, items: list) -> None:
        """Public stream message (live paper — from PaperStreams, replay — from the driver)."""
        eng = self.engine
        for item in items:
            if kind == 'order_book':
                eng.on_book(item)
                ev = self._book_events.pop(item.symbol, None)
                if ev is not None:
                    ev.set()
            elif kind == 'trades':
                eng.on_trade(item)
            elif kind in ('ticker', 'best_bid_ask'):
                self._last_tickers[item.symbol] = item
                eng.on_ticker(item)
            elif kind == 'funding':
                eng.on_funding(item)
        self._dispatch()

    async def _feed(self, s: str) -> None:
        """Live paper: subscribes the engine to the symbol's order book (and trades); no book — REST snapshot."""
        if self.replay_mode:
            return
        if s not in self._fed:
            self._fed.add(s)
            noop = _noop
            self._feed_handles.append(self.stream.subscribe('order_book', s, noop, depth=self.config.book_depth))
            if self.config.fill_on_trades:
                self._feed_handles.append(self.stream.subscribe('trades', s, noop))
            if self.config.funding_poll and self.market_type != 'spot' and self._funding_task is None:
                self._funding_task = asyncio.get_running_loop().create_task(self._funding_loop(),
                                                                            name=f'bytx:paper-funding:{self.name}')
        if not self.engine.has_book(s):
            ev = self._book_events.setdefault(s, asyncio.Event())
            try:
                await asyncio.wait_for(ev.wait(), self.config.book_wait)
            except asyncio.TimeoutError:
                pass
        if not self.engine.has_book(s):
            self._on_market('order_book', [await super().order_book(s, self.config.book_depth)])

    async def _funding_loop(self) -> None:
        interval = float(self.config.funding_poll or 60.0)
        while True:
            for s in sorted({p.symbol for p in self.engine.positions()}):
                try:
                    fr = await super().funding_rate(s)
                except asyncio.CancelledError:
                    raise
                except Exception as e:
                    logger.debug(f'{self.name} paper: funding rate {s} not received: {e!r}')
                    continue
                streams = getattr(self, '_streams', None)
                if streams is not None and streams._tap is not None:
                    from bytx.paper.record import FUNDING_SPEC
                    streams._tap(FUNDING_SPEC(s), [fr])
                self._on_market('funding', [fr])
            await self.clock.sleep(interval)

    def _dispatch(self) -> None:
        """Engine events → private streams and the position journal (if attached)."""
        events = self.engine.drain()
        if not events:
            return
        streams: Optional[PaperStreams] = getattr(self, '_streams', None)
        journal = self.journal
        for kind, item in events:
            if streams is not None and kind in ('orders', 'fills', 'positions', 'balance'):
                streams.push_private(kind, item)
            if journal is None:
                continue
            if kind == 'orders' and item.id not in self._sync_ids:
                journal._on_order_update(self, item)
            elif kind == 'positions':
                journal._on_position_update(self, item)
            elif kind == 'funding':
                self._journal_funding(item)
            elif kind == 'liquidation':
                self._journal_liquidation(item)

    def _journal_funding(self, ev: PaperFunding) -> None:
        assert self.journal is not None
        pid = self.journal.position_for(self.name, ev.symbol, ev.side)
        if pid is not None:
            self.journal._spawn(self.journal.record_funding(pid, ev.amount, ts=ev.timestamp, symbol=ev.symbol,
                                                            raw={'paper': True, 'rate': ev.rate}))

    def _journal_liquidation(self, ev: PaperLiquidation) -> None:
        assert self.journal is not None
        pid = self.journal.position_for(self.name, ev.symbol, ev.side)
        if pid is not None:
            base = ev.contracts * self._paper_market(ev.symbol).contract_size
            self.journal._spawn(self.journal.record_liquidation(
                pid, ts=ev.timestamp, symbol=ev.symbol, price=ev.price, amount=base,
                raw={'paper': True, 'liquidation_model': ev.model}))

    async def _reference_price(self, s: str, side: Optional[Side]) -> float:
        if side is not None and self.engine.best(s, side) is None:
            await self._feed(s)
        price = self.engine.best(s, side) if side is not None else self.engine.mark_price(s)
        if price:
            return float(price)
        if self.replay_mode:
            raise InvalidOrder(f'paper replay: no price for {s} (order book not received yet)', exchange=self.name)
        return await super()._reference_price(s, side)

    # ─── account ────────────────────────────────────────────────────────────

    async def balance(self) -> Balance:
        return self.engine.balance()

    async def free_collateral(self, symbol: str) -> float:
        await self.connect()
        m = self._paper_market(self.symbol(symbol))
        currency = (m.settle if m.is_contract and m.settle else m.quote).upper()
        bal = self.engine.balance()
        if currency not in bal:
            raise ExchangeError(f'no {currency} in the paper balance; available: {sorted(bal.items)}', exchange=self.name,
                                details={'symbol': m.symbol, 'currency': currency, 'currencies': sorted(bal.items)})
        return bal[currency].free

    async def positions(self, symbols: Optional[Iterable[str]] = None, *,
                        include_zero: bool = False) -> list[Position]:
        await self.connect()
        syms = {self.symbol(s) for s in symbols} if symbols else None
        return [p for p in self.engine.positions() if syms is None or p.symbol in syms]

    async def open_orders(self, symbol: Optional[str] = None) -> list[Order]:
        await self.connect()
        return self.engine.open_orders(self.symbol(symbol) if symbol else None)

    async def closed_orders(self, symbol: Optional[str] = None, *, since: Optional[int] = None,
                            limit: Optional[int] = None) -> list[Order]:
        await self.connect()
        rows = [o for o in self.engine.orders(self.symbol(symbol) if symbol else None)
                if o.status != 'open' and (since is None or (o.timestamp or 0) >= since)]
        return rows[-limit:] if limit else rows

    async def order(self, symbol: str, order_id: Optional[str] = None, *,
                    client_id: Optional[str] = None) -> Order:
        await self.connect()
        if not order_id and not client_id:
            raise ConfigError(f'order_id or client_id is required ({symbol})', exchange=self.name)
        return self.engine.order(self.symbol(symbol), order_id, client_id=client_id)

    async def _order_by_client_id(self, s: str, client_id: str) -> Order:
        return self.engine.order(s, None, client_id=client_id)

    async def find_order(self, symbol: str, client_id: str, *, timeout: float = 8.0,
                         min_scans: int = 2) -> Optional[Order]:
        await self.connect()
        if not client_id:
            raise ConfigError('find_order: client_id is required', exchange=self.name)
        try:
            return self.engine.order(self.symbol(symbol), None, client_id=client_id)
        except OrderNotFound:
            return None

    async def my_trades(self, symbol: Optional[str] = None, *, since: Optional[int] = None,
                        limit: Optional[int] = None) -> list[Fill]:
        await self.connect()
        rows = [f for f in self.engine.fills(self.symbol(symbol) if symbol else None)
                if since is None or (f.timestamp or 0) >= since]
        return rows[-limit:] if limit else rows

    async def trading_fee(self, symbol: str) -> TradingFee:
        await self.connect()
        return TradingFee(self.symbol(symbol), self.fees.maker, self.fees.taker)

    async def leverage(self, symbol: str, side: Optional[PositionSide] = None, *,
                       margin_mode: Optional[MarginMode] = None) -> Optional[float]:
        await self.connect()
        return self.engine.leverage(self.symbol(symbol))

    async def is_hedge_mode(self, symbol: Optional[str] = None, *, refresh: bool = False) -> bool:
        return bool(self._hedge)

    async def set_leverage(self, symbol: str, leverage: float, *, side: Optional[PositionSide] = None,
                           allow_open_position: bool = False) -> Optional[float]:
        """As on the exchange: integer leverage where the exchange requires it; OKX/HL — margin mode required; with an open
        position — ``PositionOpenError`` (without ``allow_open_position``). Returns the leverage.

        ``side`` — the same checks as on the exchange (:meth:`Exchange.set_leverage`: NotSupported, only this side's
        position is checked); the paper engine keeps one leverage per symbol — that one is changed."""
        if side is not None and side not in ('long', 'short'):
            raise ConfigError(f"side: 'long' or 'short' (position side), not {side!r}", exchange=self.name)
        await self.connect()
        s = self.symbol(symbol)
        if self._ex.id in _INT_LEVERAGE:
            if leverage != int(leverage):
                raise ConfigError(f'leverage on {self.name} must be an integer: {leverage}', exchange=self.name)
            leverage = int(leverage)
        mode = self._need_margin_mode(s) if self._ex.id in ('okx', 'hyperliquid') else self.margin_mode_of(s)
        if side is not None:
            await self._check_side_leverage(s, side, mode)
        if not allow_open_position and any(side is None or p.side == side for p in self.engine.positions(s)):
            raise PositionOpenError(f'position open on {s}: leverage is not changed', symbol=s,
                                    exchange=self.name)
        self.engine.set_leverage(s, float(leverage))
        self._leverage[s] = leverage
        return float(leverage)

    async def set_margin_mode(self, symbol: str, mode: MarginMode, *, leverage: Optional[float] = None) -> None:
        """Remembers the symbol's mode (paper margin is computed the same way — see the engine module)."""
        mode = _check_margin_mode(mode, self.name)
        await self.connect()
        s = self.symbol(symbol)
        self._margin_modes[s] = mode
        if leverage is not None:
            self.engine.set_leverage(s, float(leverage))
            self._leverage[s] = leverage

    async def set_position_mode(self, hedge: bool, symbol: Optional[str] = None) -> None:
        if self._ex.id in _ONE_WAY_ONLY and hedge:
            raise NotSupported('exchange supports one-way only', exchange=self.name)
        if self.engine.positions() and bool(hedge) != self.engine.hedge:
            raise ConfigError('paper: position mode can be changed only with no open positions', exchange=self.name)
        self._hedge = bool(hedge)
        self.engine.hedge = bool(hedge)

    async def transfer(self, currency: str, amount: float, from_account: str, to_account: str) -> Transfer:
        raise NotSupported('paper: transfers between accounts are not emulated', exchange=self.name)

    async def cancel_all_after(self, seconds: float, symbol: Optional[str] = None) -> Optional[int]:
        raise NotSupported('paper: the exchange dead-man switch is not emulated', exchange=self.name)

    # ─── trading ───────────────────────────────────────────────────────────

    def _new_client_id(self, role: Optional[str] = None, level_id: Optional[int] = None) -> str:
        if self._cid_rng is None:
            return super()._new_client_id(role, level_id)
        with _deterministic_ids(self._cid_rng):
            return super()._new_client_id(role, level_id)

    def _tp_sl_cids(self, request: dict) -> tuple[Optional[str], Optional[str], Optional[float], Optional[float]]:
        p = request['params']
        tp = (p.get('takeProfit') or {}).get('triggerPrice')
        sl = (p.get('stopLoss') or {}).get('triggerPrice')
        if tp is None and sl is None:
            return None, None, None, None
        attach = request.get('attach_client_id')
        tp_cid = (attach if attach else self._new_client_id('tp', 0)) if tp is not None else None
        sl_cid = None
        if sl is not None:
            sl_cid = attach if (attach and tp is None) else self._new_client_id('sl', 0)
        return tp_cid, sl_cid, tp, sl

    async def _send_order(self, request: dict, *, reconcile: bool = True) -> Order:
        """The engine instead of the exchange's create_order. ``pre_submit`` hook and journal records — as in Exchange."""
        await self._pre_submit(request)
        s = request['symbol']
        await self._feed(s)
        p = request['params']
        tp_cid, sl_cid, tp, sl = self._tp_sl_cids(request)
        req = PaperRequest(symbol=s, side=request['side'], type=request['type'], contracts=float(request['amount']),
                           price=request['price'] if request['type'] == 'limit' else None,
                           client_id=request['client_id'], post_only=bool(p.get('postOnly')),
                           time_in_force=p.get('timeInForce'), reduce_only=bool(request.get('reduce_only')),
                           take_profit=tp, stop_loss=sl, tp_client_id=tp_cid, sl_client_id=sl_cid,
                           margin_mode=self.margin_mode_of(s))
        try:
            order = self.engine.submit(req)
        except BaseException:
            self._dispatch()
            raise
        self._sync_dispatch(order.id)
        return order

    def _sync_dispatch(self, own: Optional[str]) -> None:
        """Dispatches events of a synchronous operation: its order (``own``) reaches the journal from Exchange
        (placed / canceled / replaced), other events (TP/SL, cancelled reduce-only) — as updates."""
        if own is None:
            self._dispatch()
            return
        self._sync_ids.add(own)
        try:
            self._dispatch()
        finally:
            self._sync_ids.discard(own)

    async def _attach_tp_sl(self, order: Order, request: dict) -> None:
        """Binance / HL: TP/SL as separate reduce-only triggers right after the main order (as on the exchange)."""
        legs = request['tp_sl']
        side = 'long' if request['side'] == 'buy' else 'short'
        orders = []
        for kind, price in (('stop_loss', legs.get('stop_loss')), ('take_profit', legs.get('take_profit'))):
            if price is not None:
                orders.append(await self._place_trigger(request['symbol'], kind, price, side,
                                                        contracts=float(request['amount']), client_id=None,
                                                        trigger_by=None, journal=False))
        orders.sort(key=lambda o: o.kind != 'take_profit')
        order.raw['bytx_tp_sl'] = orders
        await self._tp_sl_placed(orders)

    async def _place_trigger(self, s: str, kind: str, trigger: float, position_side: str, *,
                             contracts: Optional[float], client_id: Optional[str], trigger_by: Optional[str],
                             journal: bool = True) -> TpSlOrder:
        role = 'tp' if kind == 'take_profit' else 'sl'
        cid = client_id or self._new_client_id(role, 0)
        m = self._paper_market(s)
        price = convert.price_to_precision(self._ex, m, trigger, None)
        request: dict = {'symbol': s, 'type': 'market', 'side': 'sell' if position_side == 'long' else 'buy',
                   'amount': contracts, 'price': None, 'client_id': cid, 'reduce_only': True, 'params': {},
                   'journal_role': role}
        await self._pre_submit(request, kind, trigger_price=price,
                               trigger_by=trigger_by or self.engine.trigger_by)
        try:
            t = self.engine.submit_trigger(s, kind, price, position_side=position_side, contracts=contracts,
                                           client_id=cid, trigger_by=trigger_by)
        finally:
            self._dispatch()
        if journal:
            await self._tp_sl_placed([t])
        return t

    async def amend_order(self, symbol: str, order_id: str, *, price: Optional[float] = None,
                          size: Optional[float] = None, side: Optional[Side] = None,
                          type: str = 'limit') -> Order:
        if price is None and size is None:
            raise ConfigError(f'price and/or size is required ({symbol}, order {order_id})', exchange=self.name,
                              details={'symbol': symbol, 'order_id': order_id})
        await self.connect()
        s = self.symbol(symbol)
        m = self._paper_market(s)
        current = self.engine.order(s, order_id)
        side = side or current.side
        contracts = convert.contracts_from_size(self._ex, m, size) if size is not None else None
        p = convert.price_to_precision(self._ex, m, price, side if type == 'limit' else None) \
            if price is not None else None
        with self._journal_op(s, [order_id]):
            try:
                order = self.engine.amend(s, order_id, price=p, contracts=contracts)
            except BaseException:
                self._dispatch()
                raise
            self._sync_dispatch(order.id)
        if self.journal is not None:
            await self.journal._on_replaced(self, order_id, order)
        return order

    async def _cancel_one(self, s: str, order_id: Optional[str], client_id: Optional[str]) -> tuple[Order, bool]:
        if not order_id and not client_id:
            raise ConfigError(f'order_id or client_id is required ({s})', exchange=self.name, details={'symbol': s})
        order, ours = self.engine.cancel(s, order_id, client_id=client_id)
        self._sync_dispatch(order.id)
        return order, ours

    async def ws_place_order(self, symbol: str, side: Side, *, ws: bool = True, **kwargs: Any) -> Order:
        """Like :meth:`place_order` (paper has no separate WS path)."""
        return await self.place_order(symbol, side, **kwargs)

    async def ws_amend_order(self, symbol: str, order_id: str, *, price: Optional[float] = None,
                             size: Optional[float] = None, side: Optional[Side] = None,
                             type: str = 'limit', ws: bool = True) -> Order:
        return await self.amend_order(symbol, order_id, price=price, size=size, side=side, type=type)

    async def ws_cancel_order(self, symbol: str, order_id: Optional[str] = None, *,
                              client_id: Optional[str] = None, ws: bool = True) -> Order:
        return await self.cancel_order(symbol, order_id, client_id=client_id)

    # ─── cancels by tag / id (TP/SL — engine triggers) ─────────────────────

    async def _cancel_tp_sl_list(self, s: str, orders: list[TpSlOrder]) -> list[CancelResult]:
        out = []
        with self._journal_op(s, [o.id for o in orders] + [o.client_id for o in orders]):
            for o in orders:
                try:
                    done, ours = await self._cancel_one(s, o.id, None)
                except BytxError as e:
                    out.append(CancelResult(o.id, s, 'error', o.client_id, kind='tp_sl', error=e))
                    continue
                status = 'canceled' if ours else 'already_closed'
                out.append(CancelResult(o.id, s, status, o.client_id, kind='tp_sl', order=done))  # type: ignore[arg-type]
                if self.intents is not None:
                    self.intents._on_update(self, done)
                if self.journal is not None:
                    await self.journal._on_canceled(self, done, ours)
        return out

    async def _cancel_listed(self, symbol: Optional[str], prefix: Optional[str]) -> CancelReport:
        report = CancelReport()
        mine = [o for o in self.engine.open_orders(symbol) if prefix is None or owns(o, prefix, self._ex.id)]
        tps = [t for t in self.engine.triggers(symbol) if prefix is None or owns(t, prefix, self._ex.id)]
        for s in dict.fromkeys([o.symbol for o in mine] + [t.symbol for t in tps]):
            report.results += await self._cancel_each(s, [(o.id, o.client_id) for o in mine if o.symbol == s])
            report.results += await self._cancel_tp_sl_list(s, [t for t in tps if t.symbol == s])
        return report

    async def _cancel_ids(self, s: str, ids: list[str]) -> CancelReport:
        trig = {t.id: t for t in self.engine.triggers(s, open_only=False)}
        results: dict[str, CancelResult] = {}
        for r in await self._cancel_tp_sl_list(s, [trig[i] for i in dict.fromkeys(ids) if i in trig]):
            results[cast(str, r.id)] = r
        for r in await self._cancel_each(s, [(i, None) for i in dict.fromkeys(ids) if i not in trig]):
            results[cast(str, r.id)] = r
        return CancelReport([results[i] for i in dict.fromkeys(ids)])

    # ─── TP/SL ──────────────────────────────────────────────────────────────

    async def _protect_target(self, s: str, side: Optional[str], position_side: Optional[str],
                              size: Optional[float], contracts: Optional[float]) -> tuple[str, Optional[float]]:
        if size is not None and contracts is not None:
            raise ConfigError('at most one of size / contracts is allowed', exchange=self.name)
        m = self._paper_market(s)
        amount = (convert.contracts_from_size(self._ex, m, size) if size is not None
                  else convert.contracts_to_precision(self._ex, m, contracts) if contracts is not None else None)
        if position_side is not None and amount is not None:
            self._check_position_side(position_side)
            return position_side, amount
        pos = await self.position(s, cast(Optional[PositionSide], side or position_side))
        if pos is None:
            raise InvalidOrder(f'no {s} position for TP/SL', exchange=self.name, details={'symbol': s})
        if amount is not None and amount > pos.contracts * (1 + 1e-9):
            raise InvalidOrder(f'TP/SL amount {amount} exceeds position {pos.contracts} ({s})', exchange=self.name)
        return cast(str, pos.side), amount

    async def set_tp_sl(self, symbol: str, *, take_profit: Optional[float] = None,
                        stop_loss: Optional[float] = None, side: Optional[str] = None,
                        size: Optional[float] = None, trigger_by: Optional[TriggerBy] = None,
                        take_profit_client_id: Optional[str] = None,
                        stop_loss_client_id: Optional[str] = None,
                        contracts: Optional[float] = None,
                        position_side: Optional[str] = None) -> list[TpSlOrder]:
        """As in Exchange: engine reduce-only triggers (SL is placed first, TP before SL in the response)."""
        if take_profit is None and stop_loss is None:
            raise ConfigError('take_profit and/or stop_loss is required', exchange=self.name)
        if take_profit_client_id and take_profit_client_id == stop_loss_client_id:
            raise ConfigError('TP and SL client_id are the same', exchange=self.name)
        await self.connect()
        s = self.symbol(symbol)
        pos_side, amount = await self._protect_target(s, side, position_side, size, contracts)
        from bytx.protection import _check_prices
        _check_prices(pos_side, take_profit, stop_loss, self.name)  # type: ignore[arg-type]
        placed: list[TpSlOrder] = []
        for kind, price, cid in (('stop_loss', stop_loss, stop_loss_client_id),
                                 ('take_profit', take_profit, take_profit_client_id)):
            if price is not None:
                placed.append(await self._place_trigger(s, kind, price, pos_side, contracts=amount, client_id=cid,
                                                        trigger_by=trigger_by, journal=False))
        placed.sort(key=lambda o: o.kind != 'take_profit')
        await self._tp_sl_placed(placed)
        return placed

    async def place_tp_sl(self, symbol: str, kind: str, trigger: float, *, position_side: str,
                          size: Optional[float] = None, contracts: Optional[float] = None,
                          client_id: Optional[str] = None, trigger_by: Optional[TriggerBy] = None) -> TpSlOrder:
        if kind not in ('take_profit', 'stop_loss'):
            raise ConfigError(f"kind: 'take_profit' or 'stop_loss', not {kind!r}", exchange=self.name)
        await self.connect()
        s = self.symbol(symbol)
        pos_side, amount = await self._protect_target(s, None, position_side, size, contracts)
        return await self._place_trigger(s, kind, trigger, pos_side, contracts=amount, client_id=client_id,
                                         trigger_by=trigger_by)

    async def modify_tp_sl(self, symbol: str, order_id: str, *, take_profit: Optional[float] = None,
                           stop_loss: Optional[float] = None, size: Optional[float] = None,
                           contracts: Optional[float] = None, client_id: Optional[str] = None,
                           trigger_by: Optional[TriggerBy] = None) -> TpSlModifyResult:
        """Cancels the old trigger and places a new one (the new one only if the old one is surely gone)."""
        await self.connect()
        s = self.symbol(symbol)
        old = self.engine.trigger(s, order_id)
        price = take_profit if old.kind == 'take_profit' else stop_loss
        if price is None:
            raise ConfigError(f'{old.kind} price is required for order {order_id}', exchange=self.name)
        with self._journal_op(s, [order_id]):
            prev, ours = await self._cancel_one(s, order_id, None)
        if not ours:
            state = 'triggered' if cast(TpSlOrder, prev).state == 'triggered' else 'canceled'
            if state == 'triggered':
                return TpSlModifyResult(old='triggered', new=None, previous=cast(TpSlOrder, prev))
        m = self._paper_market(s)
        amount = (convert.contracts_from_size(self._ex, m, size) if size is not None
                  else contracts if contracts is not None else old.contracts)
        by = trigger_by or (old.raw.get('paper') or {}).get('trigger_by')
        try:
            new = await self._place_trigger(s, old.kind, price, cast(str, old.position_side), contracts=amount,
                                            client_id=client_id, trigger_by=by, journal=False)
        except BytxError as e:
            return TpSlModifyResult(old='canceled', new='rejected', previous=old, error=e)
        if self.journal is not None:
            await self.journal._on_replaced(self, order_id, new, old_canceled=True)
        return TpSlModifyResult(old='canceled', new='created', order=new, previous=old,
                                client_ids=[new.client_id] if new.client_id else [])

    async def tp_sl_orders(self, symbol: str, side: Optional[str] = None) -> list[TpSlOrder]:
        await self.connect()
        return self.engine.triggers(self.symbol(symbol), side=side)

    async def tp_sl_order(self, symbol: str, order_id: str) -> TpSlOrder:
        await self.connect()
        return self.engine.trigger(self.symbol(symbol), order_id)

    async def cancel_tp_sl(self, symbol: str, *, side: Optional[str] = None, kind: Optional[str] = None,
                           order_ids: Optional[list[str]] = None) -> int:
        await self.connect()
        s = self.symbol(symbol)
        ids = set(order_ids) if order_ids is not None else None
        targets = [t for t in self.engine.triggers(s, side=side)
                   if (kind is None or t.kind == kind) and (ids is None or t.id in ids)]
        results = await self._cancel_tp_sl_list(s, targets)
        return sum(1 for r in results if r.status == 'canceled')

    async def flatten(self, symbol: str, side: PositionSide, *, client_id_prefix: Optional[str] = None,
                      timeout: float = 10.0, poll: float = 0.5) -> FlattenReport:
        """As in Exchange; a paper position closes immediately, waiting is a single check."""
        if side not in ('long', 'short'):
            raise ConfigError(f"flatten: side — position side 'long' or 'short', not {side!r}", exchange=self.name)
        prefix = client_id_prefix if client_id_prefix is not None else self.client_id_prefix
        if not prefix:
            raise ConfigError('flatten cancels only own orders: client_id_prefix= is required '
                              '(or create_exchange(client_id_prefix=))', exchange=self.name)
        await self.connect()
        s = self.symbol(symbol)
        report = FlattenReport(symbol=s, side=side)
        mine = [o for o in self.engine.open_orders(s) if owns(o, prefix, self._ex.id)]
        report.orders = CancelReport(await self._cancel_each(s, [(o.id, o.client_id) for o in mine]))
        if report.orders.errors:
            report.errors['orders'] = cast(Exception, report.orders.errors[0].error)
        if self.market_type != 'spot':
            tps = [t for t in self.engine.triggers(s, side=side) if owns(t, prefix, self._ex.id)]
            report.tp_sl = CancelReport(await self._cancel_tp_sl_list(s, tps))
            if report.tp_sl.errors:
                report.errors['tp_sl'] = cast(Exception, report.tp_sl.errors[0].error)
        try:
            report.close = await self.close_position(s, side)
        except Exception as e:
            report.errors['close'] = self._as_error(e)
        report.flat = await self.position(s, side) is None
        if not report.flat:
            report.errors['wait'] = ExchangeError(f'position {s} {side} did not close (paper: no liquidity)',
                                                  exchange=self.name, details={'symbol': s, 'side': side})
        return report

    # ─── summary ─────────────────────────────────────────────────────────────

    def summary(self) -> dict:
        """Paper account PnL: realized / unrealized, fees, funding, liquidations, balance."""
        out = self.engine.summary()
        out['balance'] = {c: i.total for c, i in self.engine.balance().items.items()}
        return out


