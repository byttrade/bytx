class _DetUuid:
    def __init__(self, rng: random.Random) -> None:
        self._rng = rng

    def uuid4(self) -> uuid.UUID:
        return uuid.UUID(int=self._rng.getrandbits(128), version=4)


class _DetSecrets:
    def __init__(self, rng: random.Random) -> None:
        self._rng = rng

    def choice(self, seq: Any) -> Any:
        return self._rng.choice(seq)

    def token_hex(self, nbytes: int = 32) -> str:
        return format(self._rng.getrandbits(8 * nbytes), f'0{2 * nbytes}x')


@contextlib.contextmanager
def _deterministic_ids(rng: random.Random) -> Iterator[None]:
    """For the duration of one synchronous call, SDK cid generators take randomness from ``rng``."""
    from bytx import order_params
    from bytx.exchanges.hyperliquid import cloid
    from bytx.journal import client_id
    saved = (order_params.uuid, client_id.secrets, cloid.secrets)
    order_params.uuid = _DetUuid(rng)  # type: ignore[assignment]
    client_id.secrets = cloid.secrets = _DetSecrets(rng)  # type: ignore[assignment]
    try:
        yield
    finally:
        order_params.uuid, client_id.secrets, cloid.secrets = saved


def build_paper(name: str, *, market: str = 'swap', demo: Any = False, proxy: Any = None,
                timeout: float = 10.0, options: Optional[dict] = None, config: Optional[PaperConfig] = None,
                clock: Optional[Clock] = None, replay: bool = False, **kwargs: Any) -> PaperExchange:
    """PaperExchange: a ccxt instance without keys (public data only) plus the engine."""
    from bytx.transport import Proxy, build_ccxt
    proxy_obj = Proxy(proxy) if isinstance(proxy, str) else proxy
    ex = build_ccxt(name, market_type=market, demo=demo, proxy=proxy_obj, timeout_ms=int(timeout * 1000),
                    options=options)
    return PaperExchange(ex, name=name.lower(), market_type=market, demo=demo, proxy=proxy_obj, config=config,
                         clock=clock, replay=replay, **kwargs)


