"""PaperExchange — :class:`bytx.Exchange` with a virtual account.

Same public interface: ``place_order`` / ``buy`` / ``sell`` (same units, rounding,
minimums, client_id, ``pre_submit``, RiskGuard, position journal), ``cancel_*``, ``amend_order``,
``close_position`` / ``close_all`` / ``kill_switch`` / ``flatten``, TP/SL, ``balance`` /
``positions`` / ``open_orders`` / ``my_trades``, the ``ex.stream.orders/fills/positions/balance`` streams
and trackers. Orders never reach the exchange: :class:`~bytx.paper.PaperEngine` fills them against the book.

Market source:

- **live** (``create_exchange(name, paper=True)``): the exchange's public REST/WS, no keys. The first
  order on a symbol subscribes paper to the symbol's WS order book (and trades); a market order with no book in
  memory takes a REST snapshot. Funding — the rate is polled every ``PaperConfig.funding_poll`` seconds for
  symbols with a position;
- **replay** (:func:`bytx.paper.replay_exchange`): recorded streams, virtual clock, no network.

Limitations (explicit): liquidation is simplified (see :mod:`bytx.paper.engine`); the exchange
dead-man switch (``cancel_all_after``) and transfers are not emulated (:class:`~bytx.errors.NotSupported`).
Paper does **not replace** exchange demo/testnet: they have different
liquidation and margin models; parity with backtests is not proven.
"""
