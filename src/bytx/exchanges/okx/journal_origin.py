"""OKX: order origin signals for the position journal.

Source — Get order details / Transaction details (ground truth:
``tests/ground_truth/okx/order_details.json``, ``fills_history.json``):

- ``category``: ``normal`` — a regular user order; ``adl``, ``full_liquidation``,
  ``partial_liquidation``, ``delivery`` — system; ``twap`` (forced repayment, not a
  TWAP strategy), ``ddh``, ``auto_conversion`` — system, unclassified (``unknown``);
- ``source`` 6 / 7 / 13 / 25 / 34 — a regular order spawned by a trigger / TP-SL / algo /
  trailing / chase order: the parent's origin (``algoClOrdId`` / ``algoId``);
- fill ``execType``: «Not applicable to system orders such as ADL and liquidation» —
  empty for system fills (ADL or liquidation — which one can't be told from the trade);
- ``posSide``: long / short — hedge, net — one-way;
- ``cancelSource`` of a canceled order — listed in the WS Order channel (ground truth:
  ``tests/ground_truth/okx/journal_origin.json``; REST Get order details only says «Code of the
  cancellation source.»): ``1`` «Order canceled by user» — the user (us or a human);
  ``3`` risk cancel before liquidation, ``6`` — before ADL, ``7`` futures delivery, ``10``
  option expiry — system, classified; routine exchange cancels (not interference): ``2``/``22``/
  ``23`` reduce-only, ``9`` balance after funding, ``13``/``14`` FOK/IOC, ``15``/``27`` price
  limits, ``17`` closing order — position already closed, ``20`` cancel-all-after (our dead man's
  switch), ``21`` TP/SL — position closed, ``31``/``32``/``33`` post-only / self-trade / match
  limit, ``36``/``37`` TP canceled due to its SL. Other listed codes (``0`` «by system», margin,
  MMP, chase…) — unclassified (the reason is in the event); empty or unlisted — no signal.

``clOrdId`` is not autogenerated: empty — no cid.
"""
from __future__ import annotations

from typing import Optional

from bytx.journal.origin import Signal

EXCHANGE = 'okx'
AUTO_CLIENT_ID = False
CLIENT_ID_REQUIRED = False
CLIENT_ID_FIELD = 'clOrdId'

CATEGORIES: dict[str, str] = {'adl': 'adl', 'full_liquidation': 'liquidation',
                              'partial_liquidation': 'liquidation', 'delivery': 'settlement',
                              'twap': 'unknown', 'ddh': 'unknown', 'auto_conversion': 'unknown'}
CHILD_SOURCES = {'6': 'trigger', '7': 'TP/SL', '13': 'algo', '25': 'trailing stop', '34': 'chase'}
_EVENTS = {'liquidation': 'liquidated', 'adl': 'adl'}
# cancelSource (WS Order channel): code → (origin, routine exchange cancel)
CANCEL_SOURCES: dict[str, tuple[Optional[str], bool]] = {
    '1': (None, False),
    '3': ('liquidation', False), '6': ('adl', False), '7': ('settlement', False), '10': ('settlement', False),
    **{code: ('unknown', True) for code in ('2', '9', '13', '14', '15', '17', '20', '21', '22', '23', '27', '31',
                                            '32', '33', '36', '37')},
}
# other codes listed in the docs: system cancel, unclassified — a signal without origin
OTHER_CANCEL_SOURCES = frozenset({'0', '4', '34', '35', '38', '39', '42', '43', '44', '45', '46'})


def client_id_of(info: dict) -> Optional[str]:
    value = info.get('clOrdId')
    return value if isinstance(value, str) and value else None


def order_signal(info: dict) -> Optional[Signal]:
    category = info.get('category')
    if category in CATEGORIES:
        origin = CATEGORIES[category]
        return Signal(origin, f'okx: category={category}', confidence='exact' if origin != 'unknown' else None,
                      event=_EVENTS.get(origin))
    source = str(info.get('source') or '')
    if source in CHILD_SOURCES:
        return Signal(None, f'okx: source={source} (order spawned by a {CHILD_SOURCES[source]} order)', child=True,
                      parent_id=info.get('algoId') or None, parent_client_id=info.get('algoClOrdId') or None)
    return None


def fill_signal(info: dict) -> Optional[Signal]:
    if 'execType' in info and info.get('execType') == '':
        return Signal('unknown', 'okx: execType empty — system fill (ADL or liquidation)',
                      confidence='heuristic')
    return None


def cancel_signal(info: dict) -> Optional[Signal]:
    code = str(info.get('cancelSource') or '')
    if code in CANCEL_SOURCES:
        origin, expected = CANCEL_SOURCES[code]
        return Signal(origin, f'okx: cancelSource={code}', expected=expected)
    if code in OTHER_CANCEL_SOURCES:
        return Signal(None, f'okx: cancelSource={code}')
    return None


def fill_position_side(info: dict) -> Optional[str]:
    return {'long': 'long', 'short': 'short'}.get(str(info.get('posSide') or ''))
