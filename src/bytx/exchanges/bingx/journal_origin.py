"""BingX: order origin signals for the position journal.

Source — docs-v3 (ground truth: ``tests/ground_truth/bingx/journal_origin.json``,
``all_orders.json``, ``ws_order_update.json``):

- User's Force Orders ``GET /openApi/swap/v2/trade/forceOrders``: ``autoCloseType``
  ``"LIQUIDATION"`` — liquidation, ``"ADL"`` — ADL, ``limit`` up to 100. The order itself has no
  liquidation flag — liquidation order ids are taken from this endpoint (journal recovery);
- Query Order history: ``triggerOrderId`` — linked conditional order, ``isTwap`` / ``mainOrderId`` —
  TWAP child order; WS Order update push: ``ti`` — linked conditional order;
- ``positionSide`` / ``ps``: LONG / SHORT — hedge, BOTH — one-way.

No exchange-UI signal; ``clientOrderId`` is not autogenerated (empty in docs examples).

Position TP/SL (Place order ``POST /openApi/swap/v2/trade/order``, ``TAKE_PROFIT_MARKET`` /
``STOP_MARKET``) are sent without ``clientOrderID``: «clientOrderId only supports LIMIT/MARKET order type»
(``tests/ground_truth/bingx/place_order.json``). The journal recognizes such an order of its own by the id from the response, and
without it — :func:`position_tp_sl_role` + :func:`trigger_price_of` against its own ``tp_sl_set`` (like
trading-stop Bybit).
"""
from __future__ import annotations

from typing import Optional

from bytx.journal.origin import Signal

EXCHANGE = 'bingx'
AUTO_CLIENT_ID = False
CLIENT_ID_REQUIRED = False
CLIENT_ID_FIELD = 'clientOrderId'
FORCE_ORDERS_PATH = '/openApi/swap/v2/trade/forceOrders'
FORCE_ORDER_TYPES = {'LIQUIDATION': 'liquidation', 'ADL': 'adl'}
FORCE_ORDERS_LIMIT = 100
_CID_KEYS = ('clientOrderId', 'clientOrderID', 'c', 'clientOrderIdStr')


def client_id_of(info: dict) -> Optional[str]:
    for key in _CID_KEYS:
        value = info.get(key)
        if isinstance(value, str) and value:
            return value
    return None


def _nonzero(value) -> Optional[str]:
    if value in (None, '', 0, '0'):
        return None
    return str(value)


#: conditional order type (Place order ``type``; WS Order update push ``o``) → journal role
POSITION_TP_SL_TYPES: dict[str, str] = {'TAKE_PROFIT_MARKET': 'tp', 'STOP_MARKET': 'sl'}


def _order_type(info: dict) -> str:
    value = info.get('type')
    if not isinstance(value, str):
        value = info.get('o')
    return value.upper() if isinstance(value, str) else ''


def position_tp_sl_role(info: dict) -> Optional[str]:
    """TP/SL role ('tp' / 'sl') by order type; None — not TAKE_PROFIT_MARKET / STOP_MARKET."""
    return POSITION_TP_SL_TYPES.get(_order_type(info))


def trigger_price_of(info: dict) -> Optional[float]:
    """Trigger: ``stopPrice`` (REST) / ``sp`` (WS «Trigger price»); 0 / empty — None."""
    for key in ('stopPrice', 'sp'):
        try:
            value = float(info.get(key) or 0)
        except (TypeError, ValueError):
            continue
        if value:
            return value
    return None


def order_signal(info: dict) -> Optional[Signal]:
    if info.get('isTwap') in (True, 'true'):
        return Signal(None, 'bingx: isTwap — TWAP child order', child=True,
                      parent_id=_nonzero(info.get('mainOrderId')))
    parent = _nonzero(info.get('triggerOrderId')) or _nonzero(info.get('ti'))
    if parent is not None:
        return Signal(None, f'bingx: order linked to conditional order {parent}', child=True, parent_id=parent)
    return None


def fill_signal(info: dict) -> Optional[Signal]:
    return None


def cancel_signal(info: dict) -> Optional[Signal]:
    return None


def fill_position_side(info: dict) -> Optional[str]:
    ps = str(info.get('positionSide') or info.get('ps') or '').upper()
    return {'LONG': 'long', 'SHORT': 'short'}.get(ps)
