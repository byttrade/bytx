"""Hyperliquid: order origin signals for the position journal.

Source — official docs (ground truth: ``tests/ground_truth/hyperliquid/journal_origin.json``):

- WsFill: ``liquidation?: FillLiquidation`` (``liquidatedUser``, ``markPx``, ``method``:
  ``"market" | "backstop"``) — liquidation fill;
- order statuses (Query order status): ``canceled`` — «Canceled by user» (us or a human);
  ``marginCanceled`` / ``liquidatedCanceled`` — due to margin / liquidation; ``delistedCanceled`` —
  delisting; ``reduceOnlyCanceled``, ``siblingFilledCanceled`` (TP/SL), ``scheduledCancel``
  (our dead man's switch) — routine; other ``…Canceled`` — system, unclassified;
- tif ``FrontendMarket`` appears only in info responses, while the order API accepts only
  ``Alo`` / ``Ioc`` / ``Gtc`` — an order from the web UI (an inference, not a docs statement: ``heuristic``).

cloid is not autogenerated: ``null`` — no cid. The docs have no ADL flag on fills.
"""
from __future__ import annotations

from typing import Optional

from bytx.journal.origin import Signal

EXCHANGE = 'hyperliquid'
AUTO_CLIENT_ID = False
CLIENT_ID_REQUIRED = False
CLIENT_ID_FIELD = 'cloid'
CANCEL_STATUSES: dict[str, tuple[Optional[str], bool]] = {
    'canceled': (None, False),
    'marginCanceled': ('liquidation', False), 'liquidatedCanceled': ('liquidation', False),
    'delistedCanceled': ('settlement', False),
    'reduceOnlyCanceled': ('unknown', True), 'siblingFilledCanceled': ('unknown', True),
    'scheduledCancel': ('unknown', True),
    'selfTradeCanceled': ('unknown', False), 'openInterestCapCanceled': ('unknown', False),
    'vaultWithdrawalCanceled': ('unknown', False),
}
FRONTEND_TIFS = frozenset({'FrontendMarket'})


def _order(info: dict) -> dict:
    inner = info.get('order')
    return inner if isinstance(inner, dict) else info


def client_id_of(info: dict) -> Optional[str]:
    value = _order(info).get('cloid') or info.get('cloid')
    return value if isinstance(value, str) and value else None


def order_signal(info: dict) -> Optional[Signal]:
    return None


def ui_signal(info: dict) -> Optional[Signal]:
    tif = _order(info).get('tif')
    if tif in FRONTEND_TIFS:
        return Signal('exchange_ui', f'hyperliquid: tif={tif} (not accepted by the order API)', confidence='heuristic')
    return None


def fill_signal(info: dict) -> Optional[Signal]:
    liq = info.get('liquidation')
    if isinstance(liq, dict):
        return Signal('liquidation', f"hyperliquid: liquidation in fill (method={liq.get('method')})",
                      event='liquidated')
    return None


def cancel_signal(info: dict) -> Optional[Signal]:
    status = info.get('status')
    if status not in CANCEL_STATUSES:
        return None
    origin, expected = CANCEL_STATUSES[status]
    return Signal(origin, f'hyperliquid: status={status}', expected=expected)


def fill_position_side(info: dict) -> Optional[str]:
    return None   # one-way only
