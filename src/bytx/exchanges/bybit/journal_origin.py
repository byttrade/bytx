"""Bybit V5: order origin signals for the position journal.

Source — Enums Definitions (https://bybit-exchange.github.io/docs/v5/enum; ground truth:
``tests/ground_truth/bybit/journal_origin.json``):

- order and execution ``createType``: liquidation (``CreateByLiq``, ``CreateByTakeOver_PassThrough``),
  ADL, settlement (``CreateBySettle``), «- web/app» — exchange UI (``CreateByClosing`` etc.),
  exchange bots and strategies (grid, Martingale, TWAP, Iceberg, Chase, BBO, Paradigm…), child
  orders of conditional orders (``CreateByStopOrder``, ``CreateByTakeProfit``, …);
- execution ``execType``: ``BustTrade`` (Takeover liquidation), ``AdlTrade``, ``Funding``,
  ``Delivery`` / ``Settle``;
- ``cancelType``: ``CancelByUser`` (the user — us or a human), cancels before liquidation and
  ADL, on delisting; routine ones (OCO, reduce-only, position closed, DCP) are not interference;
- ``positionIdx``: 0 — one-way, 1 — Buy side, 2 — Sell side in hedge mode.

``orderLinkId`` is not autogenerated: empty — no cid.

Position TP/SL (``POST /v5/position/trading-stop``, «Passing these parameters will create
conditional orders by the system internally») arrive as conditional orders with ``stopOrderType``
``TakeProfit`` / ``StopLoss`` / ``PartialTakeProfit`` / ``PartialStopLoss`` (enum stopOrderType) and
an empty ``orderLinkId`` (no id can be passed in the request) — :func:`position_tp_sl_role`; the journal matches
them to its own ``tp_sl_set`` by trigger price.
"""
from __future__ import annotations

from typing import Optional

from bytx.journal.origin import Signal

EXCHANGE = 'bybit'
AUTO_CLIENT_ID = False
CLIENT_ID_REQUIRED = False
CLIENT_ID_FIELD = 'orderLinkId'

CREATE_TYPES: dict[str, str] = {
    'CreateByLiq': 'liquidation', 'CreateByTakeOver_PassThrough': 'liquidation',
    'CreateByAdl_PassThrough': 'adl', 'CreateBySettle': 'settlement',
    'CreateByClosing': 'exchange_ui', 'CreateByTVSignal': 'exchange_ui', 'CreateByMmRateClose': 'exchange_ui',
    'CreateByArbitrage': 'exchange_ui', 'CreateByDdh': 'exchange_ui',
    'CreateByFGridBot': 'foreign_api', 'CloseByFGridBot': 'foreign_api', 'CreateByTWAP': 'foreign_api',
    'CreateByMartingaleBot': 'foreign_api', 'CloseByMartingaleBot': 'foreign_api',
    'CreateByIceBerg': 'foreign_api', 'CreateByChaseOrder': 'foreign_api', 'CreateByBboOrder': 'foreign_api',
    'CreateByBlock_PassThrough': 'foreign_api', 'CreateByBlockTradeMovePosition_PassThrough': 'foreign_api',
    'CreateByFutureSpread': 'foreign_api',
}
CHILD_CREATE_TYPES = frozenset({'CreateByStopOrder', 'CreateByTakeProfit', 'CreateByPartialTakeProfit',
                                'CreateByStopLoss', 'CreateByPartialStopLoss', 'CreateByTrailingStop',
                                'CreateByTrailingProfit'})
_EVENTS = {'liquidation': 'liquidated', 'adl': 'adl'}
EXEC_TYPES: dict[str, tuple[str, Optional[str]]] = {
    'BustTrade': ('liquidation', 'liquidated'), 'AdlTrade': ('adl', 'adl'), 'Funding': ('funding', 'funding'),
    'Delivery': ('settlement', None), 'Settle': ('settlement', None),
}
CANCEL_TYPES: dict[str, tuple[Optional[str], bool]] = {
    'CancelByUser': (None, False),
    'CancelByPrepareLiq': ('liquidation', False), 'CancelAllBeforeLiq': ('liquidation', False),
    'CancelByPrepareAdl': ('adl', False), 'CancelAllBeforeAdl': ('adl', False),
    'CancelBySettle': ('settlement', False), 'CancelByDelivery': ('settlement', False),
    'CancelByReduceOnly': ('unknown', True), 'CancelByTpSlTsClear': ('unknown', True),
    'CancelByOCOTpCanceledBySlTriggered': ('unknown', True), 'CancelByOCOSlCanceledByTpTriggered': ('unknown', True),
    'CancelByDCP': ('unknown', True),
}


#: position TP/SL stopOrderType (enum stopOrderType) → journal role
POSITION_TP_SL_TYPES: dict[str, str] = {'TakeProfit': 'tp', 'PartialTakeProfit': 'tp',
                                        'StopLoss': 'sl', 'PartialStopLoss': 'sl'}


def position_tp_sl_role(info: dict) -> Optional[str]:
    """Position TP/SL role ('tp' / 'sl') by ``stopOrderType``; None — not a position TP/SL."""
    return POSITION_TP_SL_TYPES.get(str(info.get('stopOrderType') or ''))


def trigger_price_of(info: dict) -> Optional[float]:
    try:
        value = float(info.get('triggerPrice') or 0)
    except (TypeError, ValueError):
        return None
    return value or None


def client_id_of(info: dict) -> Optional[str]:
    value = info.get('orderLinkId')
    return value if isinstance(value, str) and value else None


def order_signal(info: dict) -> Optional[Signal]:
    ct = info.get('createType')
    if not ct:
        return None
    if ct in CREATE_TYPES:
        origin = CREATE_TYPES[ct]
        return Signal(origin, f'bybit: createType={ct}', event=_EVENTS.get(origin))
    if ct in CHILD_CREATE_TYPES:
        # a Bybit conditional order fills under the same orderId — the journal finds the parent by id
        return Signal(None, f'bybit: createType={ct} (conditional order triggered)', child=True)
    if ct == 'CreateByUser':
        return None
    return Signal('unknown', f'bybit: createType={ct} (system, not user)', confidence=None)


def fill_signal(info: dict) -> Optional[Signal]:
    et = info.get('execType')
    if et in EXEC_TYPES:
        origin, event = EXEC_TYPES[et]
        return Signal(origin, f'bybit: execType={et}', event=event)
    return order_signal(info)


def cancel_signal(info: dict) -> Optional[Signal]:
    ct = info.get('cancelType')
    if not ct or ct == 'UNKNOWN':
        return None
    origin, expected = CANCEL_TYPES.get(ct, ('unknown', False))
    return Signal(origin, f'bybit: cancelType={ct}', expected=expected)


def fill_position_side(info: dict) -> Optional[str]:
    return {'1': 'long', '2': 'short'}.get(str(info.get('positionIdx', '')))
