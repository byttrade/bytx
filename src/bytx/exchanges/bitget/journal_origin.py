"""Bitget USDT-M: order origin signals for the position journal.

Source — Get Order Detail / Get Order Fill Details (ground truth: ``tests/ground_truth/bitget/
order_detail.json``, ``fills.json``; docs https://www.bitget.com/docs/catalog/classic-contract-trade/classic-contract-trade#get-order-detail):

- ``enterPointSource`` — «WEB: Orders created on the website; API; SYS: System managed orders, usually
  generated by forced liquidation logic; ANDROID; IOS» — WEB/ANDROID/IOS — exchange UI (``exact``);
- ``tradeSide`` — burst_close_long/short, burst_buy_single / burst_sell_single («Liquidate …»),
  dte_sys_adl_* («ADL close …»), delivery_* — liquidation, ADL, settlement;
- ``orderSource`` — liquidation; profit_market / loss_market / pos_* / *_plan … — child order of a
  conditional order (parent is a trigger order, its id is not in the response).

``clientOid`` — «Customize order ID»; without it the exchange generates no id (empty in the cancel example).
"""
from __future__ import annotations

from typing import Optional

from bytx.journal.origin import Signal

EXCHANGE = 'bitget'
AUTO_CLIENT_ID = False
CLIENT_ID_REQUIRED = False
CLIENT_ID_FIELD = 'clientOid'
UI_SOURCES = frozenset({'web', 'android', 'ios'})
_LIQ_PREFIXES = ('burst_',)
_ADL_PREFIXES = ('dte_sys_adl_',)
_DELIVERY_PREFIXES = ('delivery_',)
# orderSource of child orders of conditional orders (TP/SL, plan, trailing) — Get Order Detail docs
CHILD_SOURCES = frozenset({
    'profit_market', 'loss_market', 'profit_limit', 'loss_limit', 'pos_profit_limit', 'pos_profit_market',
    'pos_loss_limit', 'pos_loss_market', 'plan_limit', 'plan_market', 'move_limit', 'move_market',
    'tracking_limit', 'tracking_market', 'profit_chase', 'loss_chase'})


def client_id_of(info: dict) -> Optional[str]:
    value = info.get('clientOid')
    return value if isinstance(value, str) and value else None


def _system(info: dict) -> Optional[Signal]:
    side = str(info.get('tradeSide') or '').lower()
    source = str(info.get('orderSource') or '').lower()
    if side.startswith(_LIQ_PREFIXES) or source == 'liquidation':
        return Signal('liquidation', f'bitget: tradeSide={side or "-"} orderSource={source or "-"}',
                      event='liquidated')
    if side.startswith(_ADL_PREFIXES):
        return Signal('adl', f'bitget: tradeSide={side}', event='adl')
    if side.startswith(_DELIVERY_PREFIXES) or source.startswith('delivery_'):
        return Signal('settlement', f'bitget: tradeSide={side} orderSource={source}')
    return None


def order_signal(info: dict) -> Optional[Signal]:
    found = _system(info)
    if found is not None:
        return found
    source = str(info.get('orderSource') or '').lower()
    if source in CHILD_SOURCES:
        return Signal(None, f'bitget: orderSource={source} — child of a conditional order', child=True)
    entry = str(info.get('enterPointSource') or '').lower()
    if entry in UI_SOURCES:
        return Signal('exchange_ui', f'bitget: enterPointSource={entry}')
    return None


def fill_signal(info: dict) -> Optional[Signal]:
    return _system(info)


def cancel_signal(info: dict) -> Optional[Signal]:
    return None


def fill_position_side(info: dict) -> Optional[str]:
    side = str(info.get('posSide') or info.get('holdSide') or '').lower()
    return side if side in ('long', 'short') else None
